const DICTS: Record<string, Dict> = { en, 'zh-CN': zhCN, 'zh-TW': zhTW, ja, ko, es, fr, de };

const FALLBACKS: { prefix: string; code: string }[] = [
  { prefix: 'zh-TW', code: 'zh-TW' },
  { prefix: 'zh', code: 'zh-CN' },
  { prefix: 'ja', code: 'ja' },
  { prefix: 'ko', code: 'ko' },
  { prefix: 'es', code: 'es' },
  { prefix: 'fr', code: 'fr' },
  { prefix: 'de', code: 'de' },
];

export function resolveLang(language: LanguageCode): string {
  if (language !== 'system') return DICTS[language] ? language : 'en';
  const nav = (navigator.language || 'en').toLowerCase();
  for (const f of FALLBACKS) {
    if (nav.startsWith(f.prefix.toLowerCase())) return f.code;
  }
  return 'en';
}

export function t(lang: string, key: string): string {
  return EXTRA[lang]?.[key] ?? DICTS[lang]?.[key] ?? EXTRA['en']?.[key] ?? en[key] ?? key;
}
